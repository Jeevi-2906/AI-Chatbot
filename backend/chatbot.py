"""
backend/chatbot.py - Gemini API Integration and Chatbot Core.

This module handles:
1. Loading API credentials and model configurations from environment variables.
2. Initializing the official Google GenAI SDK client.
3. Sending prompts to the Gemini API and returning generated responses.
"""

import os
import sys
from dotenv import load_dotenv
from google import genai
from google.genai.errors import APIError

# Ensure environment variables are loaded
load_dotenv()


def get_gemini_client():
    """
    Retrieve the Gemini API key from the environment and initialize
    the official Google GenAI client.
    
    Raises:
        ValueError: If GEMINI_API_KEY is missing or empty.
    """
    api_key = os.getenv("GEMINI_API_KEY", "").strip()
    if not api_key or api_key == "your_gemini_api_key_here":
        raise ValueError(
            "GEMINI_API_KEY is not set or is still the placeholder.\n"
            "Please obtain an API key from Google AI Studio (https://aistudio.google.com/) "
            "and add it to your .env file: GEMINI_API_KEY=your_actual_key"
        )
    return genai.Client(api_key=api_key)


def get_model_name() -> str:
    """
    Get the configured Gemini model name from environment variables.
    Defaults to 'gemini-2.5-flash'.
    """
    return os.getenv("GEMINI_MODEL", "gemini-2.5-flash").strip()


def generate_single_response(prompt: str) -> str:
    """
    Send a single prompt to the Gemini model and return the generated text response.
    
    Args:
        prompt: The input question or text from the user.
        
    Returns:
        The generated response string from Gemini.
        
    Raises:
        ValueError: If the prompt is empty or API key is not configured.
        Exception: If the API call fails.
    """
    if not prompt or not prompt.strip():
        raise ValueError("Prompt cannot be empty.")

    client = get_gemini_client()
    model_name = get_model_name()

    try:
        response = client.models.generate_content(
            model=model_name,
            contents=prompt.strip(),
        )
        if response.text:
            return response.text
        return "No response text was generated by the model."
    except APIError as e:
        raise RuntimeError(f"Gemini API Error ({e.code}): {e.message}") from e
    except Exception as e:
        raise RuntimeError(f"Unexpected error communicating with Gemini API: {str(e)}") from e


if __name__ == "__main__":
    print("=" * 60)
    print("PHASE 2 TEST: Gemini API Direct Prompt Execution")
    print(f"Configured Model: {get_model_name()}")
    print("=" * 60)

    # Test prompts to verify connection and model output
    test_prompts = [
        "What is the difference between an interpreter and a compiler in one short paragraph?",
        "Explain the concept of an API to a complete beginner in two sentences."
    ]

    try:
        for idx, test_prompt in enumerate(test_prompts, start=1):
            print(f"\n[Test Prompt {idx}]: {test_prompt}")
            print("Sending request to Gemini API...")
            reply = generate_single_response(test_prompt)
            print("-" * 40)
            print(f"[Gemini Response {idx}]:\n{reply}")
            print("-" * 40)
        print("\nAll Phase 2 test prompts succeeded!")
    except ValueError as ve:
        print(f"\n[Configuration Required]: {ve}")
        sys.exit(1)
    except Exception as err:
        print(f"\n[API Execution Error]: {err}")
        sys.exit(1)
